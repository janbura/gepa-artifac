"""Cost and time model for the remaining GEPA reproduction runs (B, 2026-11-07).

Inputs are the measured numbers in B's notes of 2026-11-07 (plan_work_2026-11-07.md) and section 2.6 of REPRODUCTION_PLAN.md.
Run:  python analysis/cost_model.py > analysis/outputs/cost_model.md
Every number in the plan's section 2.6 should be reproducible from here.
"""

A100, H100 = 128, 192            # SBU per GPU-hour
STARTUP = 0.08                   # +8 % per job for server start-up and the tail

# authors' generated tokens per run (Mtok), from their Arbor logs (notes section 3)
AUTH_MTOK = {
    "HotpotQA": {"MIPROv2": 2.07, "GEPA": 9.22, "GEPA+Merge": 6.92},   # MIPROv2 log is a restarted run (F79)
    "HoVer":    {"MIPROv2": 14.04, "GEPA": 11.90, "GEPA+Merge": 11.75},
    "IFBench":  {"MIPROv2": 7.94, "GEPA": 9.53, "GEPA+Merge": 5.16},
}
# requests per predictor call, fresh fraction (F79): HoVer 0.88, IFBench 0.94, PUPA 0.79
# MIPROv2 metric calls (F74): HotpotQA 6871, HoVer 6901 (budget 7051), IFBench 3591, LiveBench 1839, AIME ~1300 (F75)
PREDICTORS = {"HotpotQA": 4, "HoVer": 4, "IFBench": 2, "AIME": 1, "LiveBench": 1}
MIPRO_CALLS = {"HotpotQA": 6871, "HoVer": 6901, "IFBench": 3591, "AIME": 1330, "LiveBench": 1839}
TOK_PER_REQ = {"HotpotQA": 462, "HoVer": 553, "IFBench": 1120, "AIME": 5400, "LiveBench": 5400}  # authors' MIPROv2 runs; ours for math
FRESH = 0.88

# our throughput, one A100, 32 threads (notes section 4); per-stream about 50 tok/s
TPS_A100 = {"HotpotQA": 585, "HoVer": 585, "IFBench": 150, "AIME": 165, "LiveBench": 165}
TPS_A100_8THREADS = 8 * 50       # MIPROv2's effective concurrency (F76): no KV-cache cliff
TPS_H100 = {"pess": 300, "exp": 800, "opt": 1200}   # for B's long-answer benchmarks; the pilot decides

def mipro_mtok(b):
    """Fresh generations x tokens, from metric calls x predictors (F79), not from the HotpotQA log."""
    return MIPRO_CALLS[b] * PREDICTORS[b] * FRESH * TOK_PER_REQ[b] / 1e6

def mipro_hours(b):
    # bootstrapping (16 sets, one example at a time) + proposal calls (11 + 27 x predictors) are sequential:
    seq_calls = 60 + 11 + 27 * PREDICTORS[b]
    seq_h = seq_calls * (TOK_PER_REQ[b] / 50) / 3600          # one stream at 50 tok/s
    par_h = mipro_mtok(b) * 1e6 / TPS_A100_8THREADS / 3600    # trials at 8 threads
    return (seq_h + par_h) * (1 + STARTUP)

def gepa_mtok(b, variant):
    if b in AUTH_MTOK:
        return AUTH_MTOK[b][variant]
    # math: ~1,800 fresh generations + reflections (F79), GEPA+Merge ~0.75 x GEPA
    base = 1800 * TOK_PER_REQ[b] / 1e6 + 100 * 3000 / 1e6
    return base if variant == "GEPA" else 0.75 * base

def packed_gepa_hours(b, tps):
    """Six GEPA-family runs (3 seeds x GEPA, GEPA+Merge) on one server: throughput-bound."""
    mtok = 3 * (gepa_mtok(b, "GEPA") + gepa_mtok(b, "GEPA+Merge"))
    return mtok * 1e6 / tps / 3600 * (1 + STARTUP), mtok

rows = []
