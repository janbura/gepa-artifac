print("## MIPROv2-Heavy, one run, A100, 8 threads (F76)\n")
print("| Benchmark | fresh Mtok | hours | SBU | x3 seeds |")
print("|---|---|---|---|---|")
tot_mipro = 0
for b in PREDICTORS:
    h = mipro_hours(b); sbu = h * A100; tot_mipro += 3 * sbu
    print(f"| {b} | {mipro_mtok(b):.1f} | {h:.1f} | {sbu:,.0f} | {3*sbu:,.0f} |")
print(f"\nMIPROv2 total, 15 runs: {tot_mipro:,.0f} SBU\n")

print("## GEPA family, six runs packed on one server\n")
print("| Benchmark | Mtok (6 runs) | A100 hours | A100 SBU | H100 hours (pess/exp/opt) | H100 SBU (pess/exp/opt) |")
print("|---|---|---|---|---|---|")
tot_a100 = tot_h100 = {}
sumA = {"A": 0, "B_A100": 0, "B_H100_exp": 0, "B_H100_pess": 0, "B_H100_opt": 0}
for b in PREDICTORS:
    hA, mtok = packed_gepa_hours(b, TPS_A100[b])
    hH = {k: packed_gepa_hours(b, v)[0] for k, v in TPS_H100.items()}
    print(f"| {b} | {mtok:.0f} | {hA:.0f} | {hA*A100:,.0f} | {hH['pess']:.0f} / {hH['exp']:.0f} / {hH['opt']:.0f} | {hH['pess']*H100:,.0f} / {hH['exp']*H100:,.0f} / {hH['opt']*H100:,.0f} |")
    if b in ("HotpotQA", "HoVer"):
        sumA["A"] += hA * A100
    else:
        sumA["B_A100"] += hA * A100
        for k in ("pess", "exp", "opt"):
            sumA[f"B_H100_{k}"] += hH[k] * H100

