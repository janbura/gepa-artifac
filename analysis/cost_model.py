print(f"- B with GEPA family on H100: MIPROv2 {mB:,.0f} + GEPA family {sumA['B_H100_exp']:,.0f} (pess {sumA['B_H100_pess']:,.0f}, opt {sumA['B_H100_opt']:,.0f}) = {mB + sumA['B_H100_exp']:,.0f} SBU")
print(f"- B with everything on A100: MIPROv2 {mB:,.0f} + GEPA family {sumA['B_A100']:,.0f} = {mB + sumA['B_A100']:,.0f} SBU")
